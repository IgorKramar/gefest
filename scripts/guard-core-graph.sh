#!/usr/bin/env bash
# Сторож чистоты дефолтного графа крейта hef-core.
#
# hef-core держит типы, перечисления-истина и чистые переходы машин
# состояний. Его дефолтный граф зависимостей обязан оставаться пустым:
# ни рантайма, ни веб-фреймворка, ни драйвера БД. sqlx подключается только
# через опциональную фичу, которую включает hef-db.
#
# Проверка выполняется офлайн и не требует ни сети, ни базы данных —
# честный путь до зелёного есть у любого участника, включая агента в
# изолированном контейнере.
#
# --- Почему белый список, а не чёрный --------------------------------------
# Очевидная конструкция — перебрать запрещённые пакеты через
# `cargo tree -i <пакет>` и считать ненулевой код успехом. Она негодна:
# cargo выдаёт ОДНО И ТО ЖЕ сообщение «did not match any packages» и когда
# зависимости действительно нет, и когда пакета не существует вовсе.
# Проверено: `-i tokio` (нет в графе) и `-i tokyo` (не существует) дают
# идентичный вывод и код 101. Значит опечатку в списке от чистоты графа
# отличить нельзя ничем, и сторож с чёрным списком уходит в вечно-зелёный от
# одной описки — причём именно этот сторож, поставленный на пустом графе,
# никто никогда не перепроверит.
#
# Белый список свободен от этого класса отказа: сравнивается фактический
# состав графа с ожидаемым. Опечатка в ожидаемом составе делает сторожа
# красным, а не зелёным — ошибка проявляется, а не прячется. Появление
# законной зависимости требует явно расширить ALLOWED, и это видно в диффе.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

CRATE="hef-core"

# Пакеты, которым разрешено присутствовать в дефолтном графе hef-core.
# Сейчас — только сам крейт: граф обязан быть пустым.
ALLOWED=("$CRATE")

if ! tree_output=$(cargo tree -p "$CRATE" -e normal --no-default-features --prefix none 2>&1); then
    echo "guard:core-graph — cargo tree не отработал на $CRATE:" >&2
    echo "$tree_output" >&2
    echo "Дальше идти нельзя: отличить чистый граф от сломанного cargo невозможно." >&2
    exit 1
fi

# Из строк вида «hef-core v0.1.0 (/путь)» берём первое поле — имя пакета.
actual=$(awk 'NF {print $1}' <<<"$tree_output" | sort -u)

violations=0
while IFS= read -r pkg; do
    [ -z "$pkg" ] && continue
    allowed=0
    for ok in "${ALLOWED[@]}"; do
        [ "$pkg" = "$ok" ] && allowed=1 && break
    done
    if [ "$allowed" -eq 0 ]; then
        echo "guard:core-graph — в дефолтном графе $CRATE появился пакет: $pkg" >&2
        violations=1
    fi
done <<<"$actual"

if [ "$violations" -ne 0 ]; then
    echo >&2
    echo "Дефолтный граф $CRATE обязан оставаться пустым (ADR-0014)." >&2
    echo "Если зависимость законна — добавьте её в ALLOWED этого скрипта" >&2
    echo "тем же изменением, чтобы расширение границы было видно в диффе." >&2
    exit 1
fi

echo "guard:core-graph — дефолтный граф $CRATE чист (только ${ALLOWED[*]})."
