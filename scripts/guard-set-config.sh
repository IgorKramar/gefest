#!/usr/bin/env bash
# Сторож сессионно-липкого actor-контекста.
#
# --- Что охраняется --------------------------------------------------------
# RLS-контекст обязан жить внутри транзакции. Соединение возвращается в пул
# без сброса состояния — sqlx не выполняет ни DISCARD ALL, ни RESET ALL, —
# поэтому контекст, выставленный на сессию, прилипает к соединению и
# переезжает к следующему, кто возьмёт его из пула. Проявляется как
# перемежающийся показ чужих строк: невоспроизводимо, зависит от того, какое
# соединение досталось.
#
# --- Почему ловится класс, а не одна функция -------------------------------
# Очевидный вариант — искать третий аргумент set_config. Этого мало:
#
#   set_config('app.actor_id', $1, false)   -- ловится грепом по set_config
#   SET app.actor_id = '42'                 -- НЕ ловится, эффект тот же
#   SET SESSION app.actor_id = '42'         -- НЕ ловится, эффект тот же
#
# Проверено: значение, выставленное плоским SET, переживает COMMIT и остаётся
# на соединении. В крейтах вторую форму поймал бы хук after_release, но в
# migrations/** хука нет: миграции идут мимо пула приложения, и плоский SET
# там — работающий способ провести строки мимо FORCE-политик от имени
# мигратора, невидимый ни для одной другой линии защиты.
#
# Разрешено: set_config(..., true) и SET LOCAL app.* — оба живут до конца
# транзакции.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

SCAN_DIRS=(crates)
# Миграции лежат внутри crates/db, но названы отдельно: для них этот сторож —
# единственная линия защиты.
violations=0

report() {
    echo "guard:set-config — $1" >&2
    violations=1
}

# --- Форма 1: третий аргумент set_config -----------------------------------
# Ищем вызовы, где третий аргумент не является литералом true.
while IFS= read -r line; do
    [ -z "$line" ] && continue
    report "не-LOCAL set_config: $line"
done < <(
    grep -rnE "set_config\s*\([^)]*,\s*(false|FALSE)\s*\)" "${SCAN_DIRS[@]}" \
        --include='*.rs' --include='*.sql' 2>/dev/null \
        | grep -vE '^[^:]+:[0-9]+:\s*(//|--)' \
        || true
)

# --- Форма 2: плоский SET по пространству app. -----------------------------
# SET LOCAL разрешён; SET и SET SESSION — нет.
while IFS= read -r line; do
    [ -z "$line" ] && continue
    report "сессионно-липкий SET: $line"
done < <(
    grep -rniE "\bSET\s+(SESSION\s+)?app\." "${SCAN_DIRS[@]}" \
        --include='*.rs' --include='*.sql' 2>/dev/null \
        | grep -viE "SET\s+LOCAL\s+app\." \
        | grep -vE '^[^:]+:[0-9]+:\s*(//|--)' \
        || true
)

if [ "$violations" -ne 0 ]; then
    echo >&2
    echo "Actor-контекст обязан жить внутри транзакции." >&2
    echo "Разрешённые формы: set_config('app.actor_id', \$1, true) и SET LOCAL app.*" >&2
    echo "Причина — в шапке этого скрипта и в crates/db/src/pool.rs." >&2
    exit 1
fi

echo "guard:set-config — сессионно-липкого контекста не найдено (обе формы)."
