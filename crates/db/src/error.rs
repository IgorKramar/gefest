//! Ошибки прослойки доступа.

/// Результат операции с базой.
pub type DbResult<T> = Result<T, DbError>;

#[derive(Debug, thiserror::Error)]
pub enum DbError {
    #[error("ошибка базы: {0}")]
    Sqlx(#[from] sqlx::Error),

    /// CAS исчерпал попытки: строку всё это время меняли конкурирующие
    /// транзакции. Отдельный вариант, чтобы вызывающий отличал «занято» от
    /// «сломано» — первое лечится повтором позже, второе не лечится.
    #[error("CAS не сошёлся за {attempts} попыток: строку меняют конкурентно")]
    CasExhausted { attempts: u32 },

    /// Роль подключения обходит RLS. Не ошибка запроса, а негодная
    /// конфигурация: под суперпользователем политики не применяются вовсе,
    /// и любая проверка изоляции стала бы пустой.
    #[error(
        "роль обходит RLS (superuser={superuser}, bypassrls={bypassrls}) — \
         политики не применяются, проверки изоляции бессмысленны"
    )]
    RlsBypassed { superuser: bool, bypassrls: bool },
}
