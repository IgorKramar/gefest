//! Внешние идентификаторы.
//!
//! Внутри база использует `bigserial`: он компактен, хорошо ложится в
//! индексы и не утекает наружу. За пределы — в API, ссылки, логи — уходит
//! UUIDv7.
//!
//! Версия 7, а не 4: в неё встроена временная метка старшими битами,
//! поэтому идентификаторы монотонно возрастают в пределах процесса и не
//! разрушают локальность вставок в индекс. Postgres 18 умеет `uuidv7()` сам,
//! но генерация в приложении нужна раньше: идентификатор известен до того,
//! как вставка вернёт результат.

use uuid::Uuid;

/// Новый внешний идентификатор.
pub fn new_external_id() -> Uuid {
    Uuid::now_v7()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Монотонность в пределах процесса — свойство, ради которого выбрана
    /// версия 7. Одинаковая миллисекунда обрабатывается счётчиком внутри
    /// `uuid`, поэтому подряд сгенерированные значения строго возрастают.
    #[test]
    fn ids_increase_monotonically() {
        let ids: Vec<Uuid> = (0..64).map(|_| new_external_id()).collect();

        for pair in ids.windows(2) {
            assert!(
                pair[0] < pair[1],
                "UUIDv7 не возрастают: {} затем {}",
                pair[0],
                pair[1]
            );
        }
    }

    #[test]
    fn ids_are_version_7() {
        let id = new_external_id();
        assert_eq!(
            id.get_version_num(),
            7,
            "ожидалась версия 7, получена другая"
        );
    }
}
