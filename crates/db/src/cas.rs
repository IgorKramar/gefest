//! Протокол перехода состояния: событие и состояние одной транзакцией.
//!
//! Каждый переход — вставка события с `version = revision + 1` плюс
//! обновление state с проверкой `revision`. Обе операции в одной транзакции;
//! неуспех проверки означает, что кто-то опередил, и попытка повторяется с
//! перечитыванием.
//!
//! Порядок версий защищает сам CAS: номер версии вычисляется в той же
//! транзакции, где проверяется `revision`. Отдельный триггер порядка не
//! нужен и не заводится.

use crate::error::{DbError, DbResult};
use crate::pool::{ActorTx, Db};

/// Сколько раз повторять переход, прежде чем признать поражение.
///
/// Число подобрано так, чтобы пережить обычную конкуренцию двух-трёх
/// писателей и при этом не крутиться бесконечно на строке, которую держит
/// долгая транзакция. При одном операторе конфликты редки; если их станет
/// много, лечение — не увеличение числа попыток, а разбор того, кто пишет.
const MAX_ATTEMPTS: u32 = 5;

/// Итог одной попытки перехода.
pub enum Attempt<T> {
    /// Переход применён.
    Applied(T),
    /// Проверка `revision` не прошла — кто-то опередил, нужен повтор.
    Conflict,
}

/// Выполняет переход с повторами.
///
/// `step` вызывается заново на каждой попытке и обязан **перечитывать**
/// текущее состояние: смысл повтора в том, чтобы увидеть чужую запись, а не
/// применить своё решение к устаревшим данным.
///
/// Каждая попытка идёт в собственной транзакции. Откат неудачной попытки
/// обязателен — иначе следующая работала бы в транзакции, которую Postgres
/// уже пометил сбойной.
pub async fn with_retry<T, F>(db: &Db, actor: i64, mut step: F) -> DbResult<T>
where
    F: for<'a> AsyncFnMut(&'a mut ActorTx<'_>) -> DbResult<Attempt<T>>,
{
    for _attempt in 0..MAX_ATTEMPTS {
        let mut tx = db.as_actor(actor).await?;

        match step(&mut tx).await {
            Ok(Attempt::Applied(value)) => {
                tx.commit().await?;
                return Ok(value);
            }
            Ok(Attempt::Conflict) => {
                tx.rollback().await?;
                continue;
            }
            Err(err) => {
                // Откат по возможности: если транзакция уже сбойная, её
                // ошибка отката не должна подменить настоящую причину.
                let _ = tx.rollback().await;
                return Err(err);
            }
        }
    }

    Err(DbError::CasExhausted {
        attempts: MAX_ATTEMPTS,
    })
}

/// Максимум попыток — для тестов и диагностики.
pub const fn max_attempts() -> u32 {
    MAX_ATTEMPTS
}
