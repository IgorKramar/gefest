//! Супервизор процессов-исполнителей, прослойка CLI и брокер комплектов.
//!
//! **Что кладём сюда:** владение headless-процессами `claude -p --resume`,
//! разбор потока stream-json, доставку указаний в stdin с каузальным
//! `delivered` (ADR-0007), машину состояний сессии (ADR-0008), прослойку
//! запуска CLI (ADR-0009), подготовку комплекта ресурсов контейнеру задачи
//! (ADR-0006).
//!
//! **Чего сюда не кладём:** HTTP- и MCP-поверхность (в `hef-api`), SQL
//! (в `hef-db`), доменные типы (в `hef-core`).
//!
//! Секреты живут только здесь и умирают вместе с контейнером задачи:
//! исполнитель получает ресурсы единственным каналом — комплектом брокера.

