//! Типы, перечисления-истина и ошибки Гефеста.
//!
//! **Что кладём сюда:** доменные типы, перечисления, которые служат
//! источником истины для схемы БД и API, типы ошибок, чистые переходы машин
//! состояний (сессия, указание), типы событий stream-json.
//!
//! **Чего сюда не кладём:** ничего, что требует рантайма или ввода-вывода.
//! Дефолтный граф зависимостей этого крейта обязан оставаться пустым: без
//! `tokio`, `axum` и `sqlx`. Единственная зависимость — `sqlx` за
//! опциональной фичой `sqlx`, которую включает `hef-db` для производных
//! реализаций (`FromRow` и подобных). Чистота графа проверяется машинно:
//! `mise run guard:core-graph`.
//!
//! Граница описана в `ARCHITECTURE.md`, раздел «Структура (C4, container)»;
//! принята в ADR-0014.

/// Имя крейта. Существует, чтобы у скелета был предмет проверки: пустой
/// `cargo test --workspace` зелен вхолостую и не доказывает, что тестовый
/// контур вообще работает.
pub const CRATE_NAME: &str = "hef-core";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crate_name_is_set() {
        assert_eq!(CRATE_NAME, "hef-core");
    }
}
